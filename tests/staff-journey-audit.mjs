import { chromium } from 'playwright'
import { mkdtemp, rm } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { PNG } from 'pngjs'
import { createMockServer } from '../server/server.mjs'

const directory = await mkdtemp(path.join(os.tmpdir(), 'staff-journey-audit-'))
const server = createMockServer({ dataFile: path.join(directory, 'state.json') })
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const base = `http://127.0.0.1:${server.address().port}`
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] })
const page = await browser.newPage({ viewport: { width: 1365, height: 900 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const assert = (condition, message) => { if (!condition) throw new Error(message) }
const get = async route => (await (await page.request.get(`${base}/api/mock${route}`)).json())
const futureDate = new Date(Date.now() + 7 * 86_400_000).toISOString().slice(0, 10)
const photo = (shade, name) => {
  const png = new PNG({ width: 3, height: 3 })
  png.data.fill(shade)
  return { name, mimeType: 'image/png', buffer: PNG.sync.write(png) }
}
const fillBox = async ({ contents, shelf, weight = '2', condition = 'Intact', tracking = '' }) => {
  await page.locator('#rc-carrier').fill('Collection team')
  if (tracking) await page.locator('#rc-tracking').fill(tracking)
  await page.locator('#rc-contents').fill(contents)
  await page.locator('#rc-shelf').fill(shelf)
  await page.locator('#rc-weight').fill(weight)
  await page.locator('#rc-length').fill('35')
  await page.locator('#rc-width').fill('25')
  await page.locator('#rc-height').fill('18')
  await page.locator('#rc-condition').fill(condition)
}
const createLabel = async () => {
  await page.getByRole('button', { name: 'Generate QR' }).click()
  await page.waitForFunction(() => document.querySelector('#rc-label')?.value.startsWith('MIA-'))
  return page.locator('#rc-label').inputValue()
}
const openPrint = async name => {
  const popupPromise = page.waitForEvent('popup')
  await page.getByRole('button', { name }).click()
  const popup = await popupPromise
  const content = await popup.locator('body').innerText()
  await popup.close()
  return content
}

try {
  await page.goto(base)
  await page.getByRole('heading', { name: /^Ana\b/ }).waitFor()
  await page.locator('#persona').selectOption('cus_miguel')
  await page.getByRole('heading', { name: /^Miguel\b/ }).waitFor()
  await page.getByRole('button', { name: 'Request collection' }).click()
  await page.locator('#pu-address').fill('44 Sample Avenue, Hialeah, FL 33010')
  await page.locator('#pu-date').fill(futureDate)
  await page.locator('#pu-count').fill('2')
  await page.getByRole('button', { name: 'Send collection request' }).click()
  await page.getByText('44 Sample Avenue, Hialeah, FL 33010').waitFor()

  await page.locator('[data-view="receiving"]').click()
  await page.locator('#rc-source').selectOption('pickup')
  assert(await page.locator('#rc-pickup option').count() === 1, 'Uncollected request appeared in intake picker')
  await page.getByRole('button', { name: 'Mark collected' }).click()
  await page.getByText('Collected', { exact: true }).waitFor()
  assert((await page.locator('#rc-source').inputValue()) === 'pickup', 'Mark collected reset the selected receiving source')
  await page.locator('#rc-account').selectOption('MIA-ANA01')
  assert(await page.locator('#rc-pickup option').count() === 1, 'Pickup leaked into the wrong customer account')
  await page.locator('#rc-account').selectOption('MIA-MIG02')
  await page.locator('#rc-pickup').selectOption({ index: 1 })

  const firstLabel = await createLabel()
  const firstLabelRecord = await get(`/labels/${encodeURIComponent(firstLabel)}`)
  assert(firstLabelRecord.accountCode === 'MIA-MIG02', 'Label attached to the wrong customer')
  const sticker = await openPrint('Print sticker')
  assert(sticker.includes(firstLabel) && sticker.includes('MIA-MIG02'), 'Printable sticker lacks package/customer code')
  await fillBox({ contents: 'Household linens', shelf: 'B-21', condition: 'Crushed corner', tracking: 'COL-STAFF-1' })
  await page.locator('#rc-mode').selectOption('ocean')
  await page.locator('#rc-photos').setInputFiles([photo(150, 'front.png'), photo(200, 'corner.png')])
  await page.locator('#photo-previews img').nth(1).waitFor()
  await page.getByRole('button', { name: 'Confirm receipt' }).click()
  await page.getByRole('heading', { name: 'Initial receiving receipt' }).waitFor()
  const firstReceipt = await page.locator('.receipt').innerText()
  assert(firstReceipt.includes(firstLabel) && firstReceipt.includes('MIA-MIG02') && firstReceipt.includes('Crushed corner'), 'Saved receipt omitted package, account, or condition')
  const printReceipt = await openPrint('Print receipt')
  assert(printReceipt.includes(firstLabel) && printReceipt.includes('B-21') && printReceipt.includes('Crushed corner'), 'Printed receipt omitted key custody details')
  const firstPackage = await get(`/receiving/lookup?label=${encodeURIComponent(firstLabel)}`)
  assert(firstPackage.photos.length === 2 && firstPackage.events.length === 1 && firstPackage.source === 'pickup', 'First collection box did not persist photos/custody/source')
  let queue = await get('/receiving/queue')
  assert(queue.pickups[0].status === 'collected', 'Two-box collection closed after only one box')
  await page.getByRole('button', { name: 'Create draft quote' }).click()
  await page.getByRole('button', { name: 'Print quote' }).waitFor()
  const quote = await get(`/quotes/${encodeURIComponent(firstPackage.id)}`)
  assert(quote.mode === 'ocean' && quote.amountUsdCents === 1800, 'Ocean quote did not apply the configured minimum')
  const quotePrint = await openPrint('Print quote')
  assert(quotePrint.includes(firstLabel) && quotePrint.includes('Ocean'), 'Quote print omitted box or freight mode')

  await page.getByRole('button', { name: 'Receive another box' }).click()
  await page.locator('#rc-account').selectOption('MIA-MIG02')
  await page.locator('#rc-source').selectOption('pickup')
  await page.locator('#rc-pickup').selectOption({ index: 1 })
  const secondLabel = await createLabel()
  await fillBox({ contents: 'Kitchen utensils', shelf: 'B-22', weight: '1.4' })
  await page.getByRole('button', { name: 'Confirm receipt' }).click()
  await page.getByRole('heading', { name: 'Initial receiving receipt' }).waitFor()
  queue = await get('/receiving/queue')
  assert(queue.pickups[0].status === 'received', 'Two-box collection did not close after both boxes')
  assert(queue.packages.some(item => item.label === secondLabel), 'Second box missing from received queue')

  await page.getByRole('button', { name: 'Receive another box' }).click()
  await page.locator('#rc-contents').fill('Business samples')
  await page.locator('#rc-shelf').fill('C-04')
  await page.locator('.customer-create summary').click()
  await page.locator('#new-kind').selectOption('business')
  await page.locator('#new-name').fill('Harbor Supply LLC')
  await page.locator('#new-phone').fill('3055550197')
  await page.getByRole('button', { name: 'Create customer & select account' }).click()
  await page.locator('.new-customer-notice').waitFor()
  const bootstrap = await get('/bootstrap')
  const customer = bootstrap.customers.find(item => item.name === 'Harbor Supply LLC')
  assert(customer?.kind === 'business', 'New business account not saved')
  assert((await page.locator('#rc-account').inputValue()) === customer.accountCode, 'New account not selected for intake')
  assert((await page.locator('#rc-contents').inputValue()) === 'Business samples', 'Creating account discarded entered box contents')
  assert((await page.locator('#rc-shelf').inputValue()) === 'C-04', 'Creating account discarded shelf entry')
  const businessLabel = await createLabel()
  const businessLabelRecord = await get(`/labels/${encodeURIComponent(businessLabel)}`)
  assert(businessLabelRecord.accountCode === customer.accountCode, 'Business label account mismatch')
  await page.locator('#rc-carrier').fill('Walk-in customer')
  await page.locator('#rc-weight').fill('3')
  await page.locator('#rc-length').fill('40')
  await page.locator('#rc-width').fill('30')
  await page.locator('#rc-height').fill('20')
  await page.getByRole('button', { name: 'Confirm receipt' }).click()
  await page.getByRole('heading', { name: 'Initial receiving receipt' }).waitFor()
  const businessReceipt = await page.locator('.receipt').innerText()
  assert(businessReceipt.includes(customer.accountCode) && businessReceipt.includes(businessLabel), 'Business account/label missing from receipt')
  const businessDashboard = await get(`/customers/${customer.id}/dashboard`)
  assert(businessDashboard.packages.some(item => item.label === businessLabel), 'Business box missing from customer tracking')

  await page.reload()
  await page.locator('[data-view="receiving"]').click()
  await page.locator('#lookup-form input').fill(businessLabel)
  await page.locator('#lookup-form button').click()
  await page.getByRole('heading', { name: 'Initial receiving receipt' }).waitFor()
  await page.getByRole('button', { name: 'Receive another box' }).click()
  await page.locator('#rc-label').fill(businessLabel)
  await page.locator('#rc-label').press('Enter')
  await page.getByRole('heading', { name: 'Initial receiving receipt' }).waitFor()
  const repeated = await get(`/receiving/lookup?label=${encodeURIComponent(businessLabel)}`)
  assert(repeated.events.length === 1, 'Repeated scan added a duplicate custody event')
  const mobile = await browser.newPage({ viewport: { width: 320, height: 700 } })
  await mobile.goto(base)
  await mobile.locator('[data-view="receiving"]').click()
  await mobile.locator('.customer-create summary').click()
  const size = await mobile.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth }))
  assert(size.content <= size.viewport + 1, `Staff intake overflows narrow mobile viewport: ${JSON.stringify(size)}`)
  await mobile.close()
  assert(errors.length === 0, `Browser errors: ${errors.join('; ')}`)
  console.log('Staff journey audit passed: two-box collection, account-scoped pickup, QR/print, photos, condition, receipt, quote, business walk-in, persistence, duplicate scan, 320px layout.')
} finally {
  await browser.close()
  await new Promise(resolve => server.close(resolve))
  const resolved = path.resolve(directory)
  if (!resolved.startsWith(path.resolve(os.tmpdir()) + path.sep)) throw new Error('Refusing to remove unexpected test directory')
  await rm(resolved, { recursive: true, force: true })
}
