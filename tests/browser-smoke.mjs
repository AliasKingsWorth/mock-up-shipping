import { chromium } from 'playwright'
import { mkdtemp, rm } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { PNG } from 'pngjs'
import { createMockServer } from '../server/server.mjs'

const previews = path.resolve(import.meta.dirname, '../public/previews')
const directory = await mkdtemp(path.join(os.tmpdir(), 'phase1-browser-'))
const server = createMockServer({ dataFile: path.join(directory, 'state.json') })
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const url = `http://127.0.0.1:${server.address().port}`
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] })
const futureDate = new Date(Date.now() + 7 * 86_400_000).toISOString().slice(0, 10)
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 })
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto(url)
  await page.getByRole('heading', { name: /Good (morning|afternoon|evening), Ana\./ }).waitFor()
  await page.evaluate(() => document.fonts.ready)
  for (const font of ['/fonts/dm-sans.woff2', '/fonts/fraunces.woff2']) {
    if (!(await page.request.get(url + font)).ok()) throw new Error(`Local font did not load: ${font}`)
  }
  await page.screenshot({ path: path.join(previews, 'preview-desktop.png'), fullPage: true, animations: 'disabled' })
  await page.locator('#pa-carrier').fill('Collection team')
  await page.locator('#pa-tracking').fill('COLL-TEST-01')
  await page.locator('#pa-contents').fill('Books and gifts')
  await page.locator('#pa-date').fill(futureDate)
  await page.getByRole('button', { name: 'Save pre-alert' }).click()
  await page.getByText('COLL-TEST-01').waitFor()
  await page.locator('#pu-address').fill('123 Demo Lane, Miami, FL 33166')
  await page.locator('#pu-date').fill(futureDate)
  await page.getByRole('button', { name: 'Request collection' }).click()
  await page.getByText('123 Demo Lane, Miami, FL 33166').waitFor()
  await page.locator('[data-view="receiving"]').click()
  await page.screenshot({ path: path.join(previews, 'preview-intake.png'), fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Mark collected' }).click()
  await page.getByText('Collected', { exact: true }).waitFor()
  await page.locator('#rc-source').selectOption('pickup')
  await page.locator('#rc-pickup').selectOption({ index: 1 })
  await page.getByRole('button', { name: 'Generate QR' }).click()
  await page.waitForFunction(() => document.querySelector('#rc-label')?.value.startsWith('MIA-'))
  const label = await page.locator('#rc-label').inputValue()
  if (!label.startsWith('MIA-')) throw new Error('Label not generated')
  await page.locator('#rc-carrier').fill('Customer collection')
  await page.locator('#rc-tracking').fill('COLL-TEST-01')
  await page.locator('#rc-contents').fill('Books and gifts')
  await page.locator('#rc-shelf').fill('A-12')
  await page.locator('#rc-weight').fill('2.5')
  await page.locator('#rc-length').fill('35')
  await page.locator('#rc-width').fill('25')
  await page.locator('#rc-height').fill('20')
  const png = new PNG({ width: 2, height: 2 })
  png.data.fill(180)
  await page.locator('#rc-photos').setInputFiles({ name: 'box.png', mimeType: 'image/png', buffer: PNG.sync.write(png) })
  await page.locator('#photo-previews img').waitFor()
  await page.getByRole('button', { name: 'Confirm receipt' }).click()
  await page.getByRole('heading', { name: 'Initial receiving receipt' }).waitFor()
  const tracking = await (await page.request.get(`${url}/api/mock/receiving/lookup?label=${encodeURIComponent(label)}`)).json()
  if (tracking.source !== 'pickup' || tracking.photos.length !== 1 || tracking.events.length !== 1) throw new Error('Receipt did not save collection, photo, and custody event')
  const anaAfterReceipt = await (await page.request.get(`${url}/api/mock/customers/cus_ana/dashboard`)).json()
  if (anaAfterReceipt.prealerts.find(item => item.tracking === 'COLL-TEST-01')?.status !== 'received') throw new Error('Receiving did not match the pre-alert')
  const queueAfterReceipt = await (await page.request.get(`${url}/api/mock/receiving/queue`)).json()
  if (queueAfterReceipt.pickups[0].status !== 'received') throw new Error('Collection did not finish after its box was received')
  await page.getByRole('button', { name: 'Create draft quote' }).click()
  await page.locator('.receipt .notice strong').waitFor()
  if (!(await page.locator('.receipt .notice').textContent()).includes('$21.25')) throw new Error('Quote amount did not use the saved weight and rate')
  for (const name of ['Print sticker', 'Print receipt', 'Print quote']) {
    const popupPromise = page.waitForEvent('popup')
    await page.getByRole('button', { name }).click()
    const popup = await popupPromise
    await popup.locator('body').waitFor()
    if (!(await popup.locator('body').textContent()).trim()) throw new Error(`${name} opened an empty print page`)
    await popup.close()
  }
  await page.screenshot({ path: path.join(previews, 'preview-receiving.png'), fullPage: true, animations: 'disabled' })
  await page.reload()
  await page.locator('[data-view="receiving"]').click()
  await page.locator('#lookup-form input').fill('COLL-TEST-01')
  await page.locator('#lookup-form button').click()
  await page.getByRole('heading', { name: 'Initial receiving receipt' }).waitFor()
  await page.getByRole('button', { name: 'Print quote' }).waitFor()
  await page.getByRole('button', { name: 'Receive another box' }).click()
  await page.getByRole('button', { name: 'Scan with camera' }).click()
  await page.locator('#qr-video').waitFor({ state: 'visible' })
  await page.getByRole('button', { name: 'Stop camera' }).click()
  await page.locator('#qr-video').waitFor({ state: 'hidden' })
  await page.locator('#rc-account').selectOption('MIA-MIG02')
  await page.locator('#rc-carrier').fill('Walk-in customer')
  await page.locator('#rc-contents').fill('Counter drop-off tools')
  await page.getByRole('button', { name: 'Refresh queue' }).click()
  await page.waitForFunction(() => document.querySelector('#rc-contents')?.value === 'Counter drop-off tools')
  if (await page.locator('#rc-account').inputValue() !== 'MIA-MIG02') throw new Error('Queue refresh lost the selected account')
  await page.getByRole('button', { name: 'Generate QR' }).click()
  await page.waitForFunction(() => document.querySelector('#rc-label')?.value.startsWith('MIA-'))
  const walkInLabel = await page.locator('#rc-label').inputValue()
  await page.reload()
  await page.locator('[data-view="receiving"]').click()
  const qrImage = await (await page.request.get(`${url}/api/mock/labels/${encodeURIComponent(walkInLabel)}`)).json()
  await page.locator('#qr-file').setInputFiles({ name: 'label.png', mimeType: 'image/png', buffer: Buffer.from(qrImage.qr.split(',')[1], 'base64') })
  await page.getByRole('button', { name: 'Print sticker' }).waitFor()
  if (await page.locator('#rc-account').inputValue() !== 'MIA-MIG02') throw new Error('Scanned label did not select its customer')
  await page.locator('#rc-carrier').fill('Walk-in customer')
  await page.locator('#rc-contents').fill('Counter drop-off tools')
  await page.locator('#rc-shelf').fill('B-14')
  await page.locator('#rc-weight').fill('3')
  await page.locator('#rc-length').fill('40')
  await page.locator('#rc-width').fill('30')
  await page.locator('#rc-height').fill('20')
  await page.getByRole('button', { name: 'Confirm receipt' }).click()
  await page.getByRole('heading', { name: 'Initial receiving receipt' }).waitFor()
  const walkIn = await (await page.request.get(`${url}/api/mock/receiving/lookup?label=${encodeURIComponent(walkInLabel)}`)).json()
  if (walkIn.source !== 'dropoff' || walkIn.tracking !== null || walkIn.customerId !== 'cus_miguel') throw new Error('Walk-in drop-off was not saved correctly')
  await page.getByRole('button', { name: 'Receive another box' }).click()
  await page.locator('#rc-label').fill(walkInLabel)
  await page.locator('#rc-label').press('Enter')
  await page.getByRole('heading', { name: 'Initial receiving receipt' }).waitFor()
  const repeated = await (await page.request.get(`${url}/api/mock/receiving/lookup?label=${encodeURIComponent(walkInLabel)}`)).json()
  if (repeated.events.length !== 1) throw new Error('Repeated scan created another custody event')
  await page.getByRole('button', { name: 'Receive another box' }).click()
  await page.getByRole('button', { name: 'Open' }).first().click()
  await page.getByRole('heading', { name: 'Initial receiving receipt' }).waitFor()
  await page.locator('[data-view="customer"]').click()
  await page.getByText('Counter drop-off tools').first().waitFor()
  await page.locator('[data-view="receiving"]').click()
  await page.getByRole('button', { name: 'Receive another box' }).click()
  await page.locator('.customer-create summary').click()
  await page.locator('#new-name').fill('Lucía Rivera')
  await page.locator('#new-phone').fill('3055550111')
  await page.locator('#new-email').fill('lucia@example.test')
  await page.getByRole('button', { name: 'Create customer & select account' }).click()
  await page.locator('.new-customer-notice').waitFor()
  const createdCustomers = await (await page.request.get(`${url}/api/mock/bootstrap`)).json()
  const createdCustomer = createdCustomers.customers.find(item => item.email === 'lucia@example.test')
  if (!createdCustomer || await page.locator('#rc-account').inputValue() !== createdCustomer.accountCode) throw new Error('New counter customer was not selected for intake')
  await page.getByRole('button', { name: 'Generate QR' }).click()
  await page.waitForFunction(() => document.querySelector('#rc-label')?.value.startsWith('MIA-'))
  const createdLabel = await page.locator('#rc-label').inputValue()
  await page.locator('#rc-carrier').fill('Walk-in customer')
  await page.locator('#rc-contents').fill('Family gifts')
  await page.locator('#rc-shelf').fill('A-03')
  await page.locator('#rc-weight').fill('1.5')
  await page.locator('#rc-length').fill('25')
  await page.locator('#rc-width').fill('20')
  await page.locator('#rc-height').fill('20')
  await page.getByRole('button', { name: 'Confirm receipt' }).click()
  await page.getByRole('heading', { name: 'Initial receiving receipt' }).waitFor()
  await page.locator('[data-view="customer"]').click()
  await page.getByText('Family gifts').first().waitFor()
  if (await page.locator('#persona').inputValue() !== createdCustomer.id) throw new Error('Customer portal did not open the newly created account')
  const createdDashboard = await (await page.request.get(`${url}/api/mock/customers/${createdCustomer.id}/dashboard`)).json()
  if (!createdDashboard.packages.some(item => item.label === createdLabel)) throw new Error('New customer package did not appear in tracking')
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 })
  await mobile.goto(url)
  await mobile.getByRole('heading', { name: /Good (morning|afternoon|evening), Ana\./ }).waitFor()
  await mobile.evaluate(() => document.fonts.ready)
  await mobile.screenshot({ path: path.join(previews, 'preview-mobile.png'), fullPage: true, animations: 'disabled' })
  await mobile.locator('[data-view="receiving"]').click()
  await mobile.screenshot({ path: path.join(previews, 'preview-receiving-mobile.png'), fullPage: true, animations: 'disabled' })
  const mobileWidth = await mobile.evaluate(() => ({ content: document.documentElement.scrollWidth, viewport: window.innerWidth }))
  if (mobileWidth.content > mobileWidth.viewport + 1) throw new Error(`Receiving page overflows mobile width: ${JSON.stringify(mobileWidth)}`)
  await mobile.close()
  for (const width of [1024, 820, 768, 320]) {
    const responsive = await browser.newPage({ viewport: { width, height: 850 } })
    try {
      if (width === 768) await responsive.emulateMedia({ reducedMotion: 'reduce' })
      await responsive.goto(url)
      await responsive.getByRole('heading', { name: /Good (morning|afternoon|evening), Ana\./ }).waitFor()
      if (width === 768) {
        const duration = await responsive.locator('.card').first().evaluate(node => parseFloat(getComputedStyle(node).animationDuration))
        if (duration > .001) throw new Error(`Reduced-motion animation remains active: ${duration}s`)
      }
      for (const view of ['customer', 'receiving']) {
        if (view === 'receiving') await responsive.locator('[data-view="receiving"]').click()
        const size = await responsive.evaluate(() => ({ content: document.documentElement.scrollWidth, viewport: window.innerWidth }))
        if (size.content > size.viewport + 1) throw new Error(`${view} overflows at ${width}px: ${JSON.stringify(size)}`)
      }
    } finally { await responsive.close() }
  }
  await page.locator('[data-view="setup"]').click()
  await page.locator('#cfg-name').fill('Demo Freight Co')
  await page.locator('#cfg-address').fill('200 Demo Street, Miami, FL 33166')
  await page.locator('#cfg-note').fill('Write the account code on every box.')
  await page.locator('#cfg-air').fill('12')
  await page.getByRole('button', { name: 'Save demo settings' }).click()
  await page.getByText('Demo Freight Co').first().waitFor()
  const config = await (await page.request.get(`${url}/api/mock/bootstrap`)).json()
  if (config.config.miamiAddress !== '200 Demo Street, Miami, FL 33166' || config.config.receivingNote !== 'Write the account code on every box.' || config.config.airRateUsdPerKg !== 12) throw new Error('Setup did not persist')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Restore sample data' }).click()
  await page.getByText('Miami ↔ Honduras Freight').first().waitFor()
  const reset = await (await page.request.get(`${url}/api/mock/receiving/queue`)).json()
  if (reset.pickups.length !== 0 || reset.packages.some(item => item.label === walkInLabel)) throw new Error('Sample data reset did not clear demo records')
  if (errors.length) throw new Error(`Browser errors: ${errors.join('; ')}`)
  console.log('Browser flow passed: pre-alert, collection, QR file/camera, receipt, reprint, quote, walk-in customer creation and assignment, tracking, setup, reset; previews saved.')
} finally {
  await browser.close()
  await new Promise(resolve => server.close(resolve))
  const resolved = path.resolve(directory)
  if (!resolved.startsWith(path.resolve(os.tmpdir()) + path.sep)) throw new Error('Refusing to remove unexpected test directory')
  await rm(resolved, { recursive: true, force: true })
}
