import { chromium } from 'playwright'
import { mkdtemp, rm } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { createMockServer } from '../server/server.mjs'

const dir = await mkdtemp(path.join(os.tmpdir(), 'customer-journey-audit-'))
const server = createMockServer({ dataFile: path.join(dir, 'state.json') })
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const base = `http://127.0.0.1:${server.address().port}`
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const context = await browser.newContext({ permissions: ['clipboard-read', 'clipboard-write'] })
const page = await context.newPage()
const assert = (value, message) => { if (!value) throw new Error(message) }
const futureDate = new Date(Date.now() + 7 * 86_400_000).toISOString().slice(0, 10)

try {
  await page.goto(base)
  await page.getByRole('heading', { name: /Good (morning|afternoon|evening), Ana\./ }).waitFor()
  assert((await page.locator('.address-card').innerText()).includes('MIA-ANA01'), 'Ana account code is missing from address')
  await page.getByRole('button', { name: 'Copy address + code' }).click()
  const clipboard = await page.evaluate(() => navigator.clipboard.readText())
  assert(clipboard.includes('100 Example Way') && clipboard.includes('MIA-ANA01'), 'Address copy omitted address or account code')

  await page.locator('#persona').selectOption('cus_miguel')
  await page.getByRole('heading', { name: /Good (morning|afternoon|evening), Miguel\./ }).waitFor()
  assert((await page.locator('.address-card').innerText()).includes('MIA-MIG02'), 'Miguel account code is missing')
  assert(!(await page.locator('.activity-grid').innerText()).includes('PKG-1048'), 'Ana package appeared in Miguel view')
  assert((await page.locator('.activity-grid').innerText()).includes('PKG-2020'), 'Miguel package missing')
  await page.locator('#persona').selectOption('cus_ana')

  await page.locator('#pa-carrier').fill('UPS')
  await page.locator('#pa-tracking').fill('1Z-CUSTOMER-AUDIT')
  await page.locator('#pa-contents').fill('Family gifts')
  await page.locator('#pa-date').fill(futureDate)
  await page.getByRole('button', { name: 'Save pre-alert' }).click()
  await page.getByText('1Z-CUSTOMER-AUDIT').waitFor()
  await page.reload()
  await page.locator('[data-tab="prealerts"]').click()
  assert((await page.locator('.activity-grid').innerText()).includes('1Z-CUSTOMER-AUDIT'), 'Pre-alert did not survive reload')

  await page.locator('#pu-address').fill('101 Sample Road, Miami, FL 33166')
  await page.locator('#pu-date').fill(futureDate)
  await page.locator('#pu-count').fill('1')
  await page.getByRole('button', { name: 'Request collection' }).click()
  await page.getByText('101 Sample Road, Miami, FL 33166').waitFor()
  const pastCollection = await page.request.post(`${base}/api/mock/pickups`, {
    data: { customerId: 'cus_ana', address: '102 Sample Road, Miami, FL 33166', contactName: 'Ana Martínez', contactPhone: '+504 9999-1001', requestedDate: '2020-01-01', packageCount: 1 }
  })
  assert(pastCollection.status() === 400, 'Past collection date was accepted')
  await page.locator('#persona').selectOption('cus_miguel')
  await page.getByRole('heading', { name: /Good (morning|afternoon|evening), Miguel\./ }).waitFor()
  assert(!(await page.locator('.activity-grid').innerText()).includes('101 Sample Road'), 'Ana collection appeared in Miguel view')
  await page.locator('#persona').selectOption('cus_ana')
  await page.getByRole('heading', { name: /Good (morning|afternoon|evening), Ana\./ }).waitFor()

  await page.locator('[data-view="receiving"]').click()
  await page.getByRole('button', { name: 'Mark collected' }).click()
  await page.locator('#rc-source').selectOption('pickup')
  await page.getByText('Collected', { exact: true }).waitFor()
  assert((await page.locator('#rc-source').inputValue()) === 'pickup', 'Collection update reset the intake source')
  await page.locator('#rc-pickup').selectOption({ index: 1 })
  await page.getByRole('button', { name: 'Generate QR' }).click()
  await page.waitForFunction(() => document.querySelector('#rc-label')?.value.startsWith('MIA-'))
  const label = await page.locator('#rc-label').inputValue()
  await page.locator('#rc-carrier').fill('Collection team')
  await page.locator('#rc-tracking').fill('1Z-CUSTOMER-AUDIT')
  await page.locator('#rc-contents').fill('Family gifts')
  await page.locator('#rc-shelf').fill('A-17')
  await page.locator('#rc-weight').fill('2')
  await page.locator('#rc-length').fill('30')
  await page.locator('#rc-width').fill('20')
  await page.locator('#rc-height').fill('15')
  await page.getByRole('button', { name: 'Confirm receipt' }).click()
  await page.getByRole('heading', { name: 'Initial receiving receipt' }).waitFor()
  await page.getByRole('button', { name: 'Create draft quote' }).click()
  await page.locator('[data-view="customer"]').click()
  await page.locator('[data-tab="packages"]').click()
  await page.locator(`[data-package]`).filter({ hasText: label }).click()
  const detail = await page.locator('.journey').innerText()
  assert(detail.includes('Family gifts') && detail.includes('Received in Miami'), 'New box contents/journey missing')
  assert(detail.includes('A-17') && detail.includes('Draft freight estimate'), 'New box shelf/quote missing')
  await page.locator('[data-tab="prealerts"]').click()
  const prealert = page.locator('.package-row').filter({ hasText: '1Z-CUSTOMER-AUDIT' })
  assert((await prealert.innerText()).toLowerCase().includes('received'), 'Pre-alert did not change to received')
  await page.locator('[data-tab="pickups"]').click()
  assert((await page.locator('.activity-grid').innerText()).toLowerCase().includes('received'), 'Collection did not complete')

  const denied = await page.request.get(`${base}/api/mock/packages/${label}?customerId=cus_miguel`)
  assert(denied.status() === 404, 'Another customer could read the new box detail')

  await page.locator('[data-view="receiving"]').click()
  await page.getByRole('button', { name: 'Receive another box' }).click()
  await page.locator('.customer-create summary').click()
  await page.locator('#new-kind').selectOption('business')
  await page.locator('#new-name').fill('Rivera Hardware LLC')
  await page.locator('#new-phone').fill('+1 305 555 0199')
  await page.locator('#new-email').fill('rivera@example.test')
  await page.getByRole('button', { name: 'Create customer & select account' }).click()
  await page.locator('.new-customer-notice').getByText('Rivera Hardware LLC').waitFor()
  const newCode = await page.locator('#rc-account').inputValue()
  assert(newCode.startsWith('MIA-C'), 'New customer was not selected in the receiving form')
  assert((await page.locator('#rc-contents').inputValue()) === '', 'New account inherited box contents from the last intake')
  await page.locator('[data-view="customer"]').click()
  await page.getByRole('heading', { name: /Good (morning|afternoon|evening), Rivera\./ }).waitFor()
  assert((await page.locator('.address-card').innerText()).includes(newCode), 'New account does not show its Miami code before first box')
  assert((await page.locator('.activity-grid').innerText()).includes('Your first box'), 'New account lacks a useful empty tracking state')
  await page.locator('[data-view="receiving"]').click()
  assert((await page.locator('#rc-account').inputValue()) === newCode, 'Returning from customer view changed the selected account')
  await page.getByRole('button', { name: 'Generate QR' }).click()
  await page.waitForFunction(() => document.querySelector('#rc-label')?.value.startsWith('MIA-'))
  const newLabel = await page.locator('#rc-label').inputValue()
  await page.locator('#rc-carrier').fill('Walk-in customer')
  await page.locator('#rc-contents').fill('Hardware samples')
  await page.locator('#rc-shelf').fill('B-19')
  await page.locator('#rc-weight').fill('1.5')
  await page.locator('#rc-length').fill('25')
  await page.locator('#rc-width').fill('25')
  await page.locator('#rc-height').fill('20')
  await page.getByRole('button', { name: 'Confirm receipt' }).click()
  await page.getByRole('heading', { name: 'Initial receiving receipt' }).waitFor()
  const newReceipt = await page.locator('.receipt').innerText()
  assert(newReceipt.includes(newCode) && newReceipt.includes(newLabel), 'First receipt omitted new account or label')
  await page.locator('[data-view="customer"]').click()
  await page.getByRole('heading', { name: /Good (morning|afternoon|evening), Rivera\./ }).waitFor()
  assert((await page.locator('.activity-grid').innerText()).includes('Hardware samples'), 'New customer cannot see first box')
  assert((await page.locator('.journey').innerText()).includes('B-19'), 'New customer journey missing shelf')
  await page.reload()
  await page.locator('#persona').selectOption('cus_ana')
  await page.locator('#persona').selectOption({ label: 'Rivera Hardware LLC · Customer' })
  await page.getByRole('heading', { name: /Good (morning|afternoon|evening), Rivera\./ }).waitFor()
  assert((await page.locator('.activity-grid').innerText()).includes(newLabel), 'New account/package did not persist after reload')
  const deniedNew = await page.request.get(`${base}/api/mock/packages/${newLabel}?customerId=cus_ana`)
  assert(deniedNew.status() === 404, 'Ana could read the new customer package')
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 } })
  await mobile.goto(base)
  await mobile.locator('[data-view="receiving"]').click()
  await mobile.locator('.customer-create summary').click()
  const mobileSize = await mobile.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth }))
  assert(mobileSize.content <= mobileSize.viewport + 1, `New customer form overflows mobile: ${JSON.stringify(mobileSize)}`)
  await mobile.close()
  console.log('Customer journey audit passed: both personas, address copy, pre-alert, collection without form reset, receipt, quote, journey, privacy, persistence, and new counter account with first box.')
} finally {
  await browser.close()
  await new Promise(resolve => server.close(resolve))
  const resolved = path.resolve(dir)
  if (!resolved.startsWith(path.resolve(os.tmpdir()) + path.sep)) throw new Error('Refusing to remove unexpected test directory')
  await rm(resolved, { recursive: true, force: true })
}
